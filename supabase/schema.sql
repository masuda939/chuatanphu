-- Run this script in Supabase Dashboard → SQL Editor to enable shared community chat.
create table if not exists public.temple_chat_messages (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 28),
  text text not null check (char_length(text) between 1 and 220),
  created_at timestamptz not null default now()
);

alter table public.temple_chat_messages enable row level security;
grant select, insert on table public.temple_chat_messages to anon, authenticated;
grant usage, select on sequence public.temple_chat_messages_id_seq to anon, authenticated;

drop policy if exists "Anyone can read recent temple chat" on public.temple_chat_messages;
create policy "Anyone can read recent temple chat"
  on public.temple_chat_messages for select to anon, authenticated
  using (created_at > now() - interval '7 days');

drop policy if exists "Anyone can send a temple chat message" on public.temple_chat_messages;
create policy "Anyone can send a temple chat message"
  on public.temple_chat_messages for insert to anon, authenticated
  with check (
    char_length(name) between 1 and 28
    and char_length(text) between 1 and 220
    and created_at > now() - interval '1 minute'
  );

create index if not exists temple_chat_messages_created_at_idx
  on public.temple_chat_messages (created_at desc);

-- Realtime sends new shared messages to currently connected visitors.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'temple_chat_messages'
  ) then
    alter publication supabase_realtime add table public.temple_chat_messages;
  end if;
end $$;
